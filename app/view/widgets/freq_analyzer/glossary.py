    """将 routeKey 翻译成用户可见的中文面板名(用于弹窗标题)"""
    mapping = {
        "corpusImport": "语料导入与清洗",
        "freqAnalyzer": "词频分析",
        "wordAnalysis": "词语分析",
        "keywordList": "主题词分析",
        "concordance": "语境分析",
        "sentiment": "情感分析",
        "collocation": "搭配分析",
        "construction": "构式搭配强度",
        "wordCloud": "词语云图",
        "network": "共现网络图",
        "dependency": "句法依存图",
    }
    return mapping.get(routeKey, routeKey)
