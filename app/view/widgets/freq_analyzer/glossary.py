def getGlossaryFor(routeKey: str) -> List[TermTuple]:
    """根据子面板 routeKey 返回术语列表

    Args:
        routeKey: FreqAnalyzerInterface.segmented 的 key
                  (corpusImport / freqAnalyzer / ...)

    Returns:
        [(术语, 释义), ...],若找不到则返回空列表
    """
    return _GLOSSARY.get(routeKey, [])


def getAllGlossary() -> Dict[str, List[TermTuple]]:
    """返回全部术语字典(供调试 / 文档生成使用)"""
    return _GLOSSARY


